package com.jarvis.assistant

import android.app.Activity
import android.content.ActivityNotFoundException
import android.content.Intent
import android.os.BatteryManager
import android.os.Bundle
import android.speech.RecognizerIntent
import android.speech.tts.TextToSpeech
import androidx.activity.ComponentActivity
import androidx.activity.compose.setContent
import androidx.activity.result.contract.ActivityResultContracts
import androidx.compose.foundation.background
import androidx.compose.foundation.border
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.shape.CircleShape
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Brush
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import androidx.activity.compose.rememberLauncherForActivityResult
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

class MainActivity : ComponentActivity() {

    private var speech: TextToSpeech? = null
    private var speechReady = false

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        speech = TextToSpeech(this) { status ->
            if (status == TextToSpeech.SUCCESS) {
                val result = speech?.setLanguage(Locale.US)

                speechReady =
                    result != null &&
                    result != TextToSpeech.LANG_MISSING_DATA &&
                    result != TextToSpeech.LANG_NOT_SUPPORTED

                speech?.setPitch(0.85f)
                speech?.setSpeechRate(0.95f)
            }
        }

        setContent {
            JarvisScreen()
        }
    }

    private fun speak(text: String) {
        if (!speechReady) return

        speech?.speak(
            text,
            TextToSpeech.QUEUE_FLUSH,
            null,
            "jarvis-response"
        )
    }

    private fun openWebsite(url: String): String {
        return try {
            val intent = Intent(
                Intent.ACTION_VIEW,
                android.net.Uri.parse(url)
            )
            startActivity(intent)
            "Website browser ko hand off kar di."
        } catch (_: ActivityNotFoundException) {
            "Website kholne ke liye browser nahi mila."
        } catch (_: SecurityException) {
            "Android ne website kholne ki permission nahi di."
        }
    }

    private fun executeCommand(input: String): String {
        val command = input
            .lowercase(Locale.ROOT)
            .trim()
            .removePrefix("wake up jarvis")
            .removePrefix("hey jarvis")
            .removePrefix("jarvis")
            .trim()
            .trimEnd('?', '.', '!')

        return when {
            command.isBlank() ->
                "Online and ready. How can I help?"

            command in listOf(
                "hello", "hi", "hey", "namaste", "नमस्ते"
            ) ->
                "Hello! I am ready for your command."

            command.contains("time") ||
            command.contains("samay") ||
            command.contains("समय") -> {
                val time = SimpleDateFormat(
                    "h:mm a",
                    Locale.getDefault()
                ).format(Date())

                "The time is $time."
            }

            command.contains("date") ||
            command.contains("what day") ||
            command.contains("tareekh") ||
            command.contains("तारीख") -> {
                val date = SimpleDateFormat(
                    "EEEE, d MMMM yyyy",
                    Locale.getDefault()
                ).format(Date())

                "Today is $date."
            }

            command.contains("battery") ||
            command.contains("बैटरी") -> {
                val batteryManager =
                    getSystemService(BATTERY_SERVICE) as BatteryManager

                val level = batteryManager.getIntProperty(
                    BatteryManager.BATTERY_PROPERTY_CAPACITY
                )

                if (level in 0..100) {
                    "Battery is at $level percent."
                } else {
                    "Battery information is unavailable."
                }
            }

            command == "open youtube" ->
                openWebsite("https://www.youtube.com/")

            command == "open google" ->
                openWebsite("https://www.google.com/")

            command == "open maps" ->
                openWebsite("https://maps.google.com/")

            command == "open wikipedia" ->
                openWebsite("https://www.wikipedia.org/")

            command.startsWith("search for ") ||
            command.startsWith("search ") -> {
                val query = command
                    .removePrefix("search for ")
                    .removePrefix("search ")
                    .trim()

                if (query.isBlank()) {
                    "Tell me what you want to search for."
                } else {
                    openWebsite(
                        "https://www.google.com/search?q=" +
                            android.net.Uri.encode(query)
                    )
                }
            }

            command in listOf(
                "help", "commands", "what can you do"
            ) ->
                "Try: What time is it? Today's date. " +
                    "Battery status. Open YouTube. Open Google. " +
                    "Open Maps. Open Wikipedia. " +
                    "Or search for something."

            command.contains("who are you") ->
                "I am Jarvis, your starter Android voice assistant."

            command.contains("thank") ->
                "You are welcome."

            else ->
                "That command is not available in this starter version. " +
                    "Say help for supported commands."
        }
    }

    @Composable
    private fun JarvisScreen() {
        val cyan = Color(0xFF75F6FF)
        val background = Color(0xFF050C16)
        val panel = Color(0xFF102235)

        var input by remember { mutableStateOf("") }
        var voiceEnabled by remember { mutableStateOf(true) }
        var status by remember { mutableStateOf("SYSTEM READY") }
        var messages by remember {
            mutableStateOf(
                listOf(
                    "JARVIS: Welcome. Tap SPEAK or type a command."
                )
            )
        }

        fun addMessage(message: String) {
            messages = (messages + message).takeLast(20)
        }

        fun handleCommand(raw: String) {
            if (raw.isBlank()) return

            addMessage("YOU: $raw")
            val response = executeCommand(raw)
            addMessage("JARVIS: $response")
            status = "READY FOR YOUR NEXT COMMAND"

            if (voiceEnabled) {
                speak(response)
            }
        }

        val voiceLauncher = rememberLauncherForActivityResult(
            ActivityResultContracts.StartActivityForResult()
        ) { result ->
            if (result.resultCode == Activity.RESULT_OK) {
                val transcript = result.data
                    ?.getStringArrayListExtra(
                        RecognizerIntent.EXTRA_RESULTS
                    )
                    ?.firstOrNull()

                if (transcript.isNullOrBlank()) {
                    status = "NO SPEECH RECEIVED — TRY AGAIN"
                } else {
                    handleCommand(transcript)
                }
            } else {
                status = "VOICE INPUT CLOSED — TAP SPEAK TO RETRY"
            }
        }

        MaterialTheme(
            colorScheme = darkColorScheme(
                primary = cyan,
                background = background,
                surface = panel,
                onPrimary = background,
                onBackground = Color.White,
                onSurface = Color.White
            )
        ) {
            Surface(
                modifier = Modifier.fillMaxSize(),
                color = background
            ) {
                Column(
                    modifier = Modifier
                        .fillMaxSize()
                        .windowInsetsPadding(WindowInsets.safeDrawing)
                        .imePadding()
                        .verticalScroll(rememberScrollState())
                        .padding(20.dp),
                    horizontalAlignment = Alignment.CenterHorizontally
                ) {
                    Text(
                        text = "J.A.R.V.I.S.",
                        fontSize = 30.sp,
                        fontWeight = FontWeight.Bold,
                        color = cyan,
                        letterSpacing = 5.sp
                    )

                    Text(
                        text = "PERSONAL VOICE CONSOLE",
                        fontSize = 10.sp,
                        color = Color(0xFF8CA9BD),
                        letterSpacing = 2.sp
                    )

                    Spacer(Modifier.height(28.dp))

                    Box(
                        modifier = Modifier
                            .size(220.dp)
                            .border(
                                width = 2.dp,
                                color = cyan.copy(alpha = 0.5f),
                                shape = CircleShape
                            )
                            .padding(16.dp)
                            .border(
                                width = 5.dp,
                                color = cyan.copy(alpha = 0.75f),
                                shape = CircleShape
                            )
                            .padding(16.dp)
                            .background(
                                brush = Brush.radialGradient(
                                    listOf(
                                        Color(0xFF1D5269),
                                        Color(0xFF071521)
                                    )
                                ),
                                shape = CircleShape
                            )
                            .border(
                                width = 1.dp,
                                color = cyan,
                                shape = CircleShape
                            ),
                        contentAlignment = Alignment.Center
                    ) {
                        Column(
                            horizontalAlignment = Alignment.CenterHorizontally
                        ) {
                            Text(
                                text = "JARVIS",
                                color = cyan,
                                fontSize = 24.sp,
                                fontWeight = FontWeight.Bold
                            )

                            Spacer(Modifier.height(8.dp))

                            Text(
                                text = "ONLINE",
                                color = Color.White,
                                fontSize = 10.sp,
                                letterSpacing = 3.sp
                            )
                        }
                    }

                    Spacer(Modifier.height(20.dp))

                    Text(
                        text = status,
                        color = cyan,
                        fontSize = 11.sp
                    )

                    Spacer(Modifier.height(18.dp))

                    Button(
                        onClick = {
                            speech?.stop()

                            val intent = Intent(
                                RecognizerIntent.ACTION_RECOGNIZE_SPEECH
                            ).apply {
                                putExtra(
                                    RecognizerIntent.EXTRA_LANGUAGE_MODEL,
                                    RecognizerIntent.LANGUAGE_MODEL_FREE_FORM
                                )
                                putExtra(
                                    RecognizerIntent.EXTRA_LANGUAGE,
                                    "en-IN"
                                )
                                putExtra(
                                    RecognizerIntent.EXTRA_PROMPT,
                                    "Speak to Jarvis"
                                )
                                putExtra(
                                    RecognizerIntent.EXTRA_MAX_RESULTS,
                                    1
                                )
                            }

                            try {
                                status = "OPENING VOICE INPUT"
                                voiceLauncher.launch(intent)
                            } catch (_: ActivityNotFoundException) {
                                status = "VOICE SERVICE UNAVAILABLE"
                                addMessage(
                                    "JARVIS: No speech-input app was found. " +
                                        "Please use typed commands."
                                )
                            } catch (_: SecurityException) {
                                status = "VOICE INPUT BLOCKED"
                                addMessage(
                                    "JARVIS: Android blocked voice input. " +
                                        "Please use typed commands."
                                )
                            }
                        },
                        modifier = Modifier
                            .fillMaxWidth()
                            .height(54.dp)
                    ) {
                        Text("SPEAK TO JARVIS")
                    }

                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.SpaceBetween
                    ) {
                        Text("Spoken replies")

                        Switch(
                            checked = voiceEnabled,
                            onCheckedChange = {
                                voiceEnabled = it
                                if (!it) speech?.stop()
                            }
                        )
                    }

                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.spacedBy(8.dp)
                    ) {
                        OutlinedButton(
                            onClick = { handleCommand("What time is it?") },
                            modifier = Modifier.weight(1f)
                        ) {
                            Text("Time")
                        }

                        OutlinedButton(
                            onClick = { handleCommand("Battery status") },
                            modifier = Modifier.weight(1f)
                        ) {
                            Text("Battery")
                        }

                        OutlinedButton(
                            onClick = { handleCommand("Help") },
                            modifier = Modifier.weight(1f)
                        ) {
                            Text("Help")
                        }
                    }

                    Spacer(Modifier.height(14.dp))

                    OutlinedTextField(
                        value = input,
                        onValueChange = { input = it },
                        label = { Text("Type a command") },
                        modifier = Modifier.fillMaxWidth(),
                        singleLine = true,
                        shape = RoundedCornerShape(14.dp)
                    )

                    Button(
                        onClick = {
                            val command = input
                            input = ""
                            handleCommand(command)
                        },
                        enabled = input.isNotBlank(),
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(top = 8.dp)
                    ) {
                        Text("SEND COMMAND")
                    }

                    Spacer(Modifier.height(18.dp))

                    Card(
                        modifier = Modifier.fillMaxWidth(),
                        colors = CardDefaults.cardColors(
                            containerColor = panel
                        )
                    ) {
                        Column(
                            modifier = Modifier.padding(16.dp),
                            verticalArrangement = Arrangement.spacedBy(14.dp)
                        ) {
                            Text(
                                text = "CONVERSATION",
                                color = cyan,
                                fontSize = 11.sp,
                                letterSpacing = 2.sp
                            )

                            messages.forEach { message ->
                                Text(
                                    text = message,
                                    fontSize = 14.sp,
                                    color = if (message.startsWith("YOU:")) {
                                        Color(0xFFAFC7FF)
                                    } else {
                                        Color(0xFFE2F7FF)
                                    }
                                )
                            }
                        }
                    }

                    Spacer(Modifier.height(16.dp))

                    Text(
                        text = "Starter build • Tap-to-speak only\n" +
                            "Speech input may use your provider's online service. " +
                            "Conversation is not saved by this app.",
                        color = Color(0xFF8CA9BD),
                        fontSize = 11.sp
                    )
                }
            }
        }
    }

    override fun onDestroy() {
        speech?.stop()
        speech?.shutdown()
        speech = null
        super.onDestroy()
    }
}
