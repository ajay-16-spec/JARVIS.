class MainActivity : ComponentActivity() {

    private var speech: TextToSpeech? = null
    private var speechReady = false

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        speech = TextToSpeech(this) { status ->
            if (status == TextToSpeech.SUCCESS) {
                val result = speech?.setLanguage(Locale.US)

                speechReady =
                    result != null &&
                    result != TextToSpeech.LANG_MISSING_DATA &&
                    result != TextToSpeech.LANG_NOT_SUPPORTED

                speech?.setPitch(0.85f)
                speech?.setSpeechRate(0.95f)
            }
        }

        setContent {
            JarvisScreen()
        }
    }

    private fun speak(text: String) {
        if (!speechReady) return

        speech?.speak(
            text,
            TextToSpeech.QUEUE_FLUSH,
            null,
            "jarvis-response"
        )
    }

    private fun openWebsite(url: String): String {
        return try {
            val intent = Intent(
                Intent.ACTION_VIEW,
                android.net.Uri.parse(url)
            )
            startActivity(intent)
            "Website browser ko hand off kar di."
        } catch (_: ActivityNotFoundException) {
            "Website kholne ke liye browser nahi mila."
        } catch (_: SecurityException) {
            "Android ne website kholne ki permission nahi di."
        }
    }

